package com.practice.constructors1;

public class Employee {
	
	String employeeName;
	int age;
	int salary;
	String address;
	
	Employee(String _employeeName, int _age, int _salary, String _address){
		
		this.employeeName = _employeeName;
		this.age = _age;
		this.salary = _salary;
		this.address = _address;
		
	}

}
